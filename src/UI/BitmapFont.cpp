    void drawChar(SDL_Renderer* renderer, char c, float x, float y, float scale, SDL_Color color)
    {
        // Clamp character to supported ASCII range [32, 127]
        int charVal = static_cast<int>(c);
        if (charVal < 32 || charVal > 127)
        {
            charVal = 63; // Render '?' for unsupported characters
        }

        int index = charVal - 32;
        SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);

        // Draw character pixels
        for (int row = 0; row < 8; ++row)
        {
            unsigned char rowData = font[index][row];
            for (int col = 0; col < 8; ++col)
            {
                // Most-significant bit represents column 0
                if (rowData & (1 << (7 - col)))
                {
                    SDL_FRect pixelRect;
                    pixelRect.x = x + col * scale;
                    pixelRect.y = y + row * scale;
                    pixelRect.w = scale;
                    pixelRect.h = scale;

                    SDL_RenderFillRect(renderer, &pixelRect);
                }
            }
        }
    }

    void drawText(SDL_Renderer* renderer, const std::string& text, float x, float y, float scale, SDL_Color color)
    {
        float currentX = x;
        for (char c : text)
        {
            // Simple newline support
            if (c == '\n')
            {
                currentX = x;
                y += 10.0f * scale; // Move down one row with line spacing
                continue;
            }

            drawChar(renderer, c, currentX, y, scale, color);
            currentX += 8.0f * scale; // Advance column width
        }
    }
