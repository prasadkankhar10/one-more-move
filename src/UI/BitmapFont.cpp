    void drawChar(SDL_Renderer* renderer, char c, float x, float y, float scale, SDL_Color color)
    {
        int charVal = static_cast<unsigned char>(c);
        if (charVal < 32 || charVal > 127) charVal = 63; // '?'
        int index = charVal - 32;

        float ix = std::floor(x);
        float iy = std::floor(y);

        SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);

        // Merge contiguous horizontal pixels into solid rectangular bars for razor-sharp rendering
        for (int row = 0; row < 8; ++row)
        {
            unsigned char rowData = font[index][row];
            if (rowData == 0) continue;

            int col = 0;
            while (col < 8)
            {
                if (rowData & (1 << (7 - col)))
                {
                    int startCol = col;
                    while (col < 8 && (rowData & (1 << (7 - col))))
                    {
                        col++;
                    }
                    int runLen = col - startCol;

                    SDL_FRect rect;
                    rect.x = ix + startCol * scale;
                    rect.y = iy + row * scale;
                    rect.w = runLen * scale;
                    rect.h = scale;

                    SDL_RenderFillRect(renderer, &rect);
                }
                else
                {
                    col++;
                }
            }
        }
    }

    float getTextWidth(const std::string& text, float scale)
    {
        float maxWidth = 0.0f;
        float curWidth = 0.0f;
        for (char c : text)
        {
            if (c == '\n')
            {
                if (curWidth > maxWidth) maxWidth = curWidth;
                curWidth = 0.0f;
            }
            else
            {
                curWidth += 9.0f * scale; // 8px glyph + 1px spacing
            }
        }
        return std::max(maxWidth, curWidth);
    }

    void drawText(SDL_Renderer* renderer, const std::string& text, float x, float y, float scale, SDL_Color color)
    {
        float shadowOffset = std::max(1.0f, std::round(scale * 0.75f));
        SDL_Color shadowColor = { 0, 0, 0, 220 };

        // Pass 1: Crisp drop shadow behind all glyphs
        float curX = x + shadowOffset;
        float curY = y + shadowOffset;
        for (char c : text)
        {
            if (c == '\n')
            {
                curX = x + shadowOffset;
                curY += 11.0f * scale; // Row height
                continue;
            }
            drawChar(renderer, c, curX, curY, scale, shadowColor);
            curX += 9.0f * scale;
        }

        // Pass 2: Sharp foreground text
        curX = x;
        curY = y;
        for (char c : text)
        {
            if (c == '\n')
            {
                curX = x;
                curY += 11.0f * scale;
                continue;
            }
            drawChar(renderer, c, curX, curY, scale, color);
            curX += 9.0f * scale;
        }
    }

    float drawTextWrapped(SDL_Renderer* renderer, const std::string& text, float x, float y, float maxWidth, float scale, SDL_Color color, float lineSpacing)
    {
        float curY = y;
        float charW = 9.0f * scale;
        
        std::string currentLine = "";
        std::string currentWord = "";

        auto flushWord = [&](bool isNewline) {
            float wordWidth = currentWord.length() * charW;
            float lineWithWordWidth = (currentLine.empty() ? 0.0f : (currentLine.length() + 1) * charW) + wordWidth;

            if (!currentLine.empty() && lineWithWordWidth > maxWidth)
            {
                drawText(renderer, currentLine, x, curY, scale, color);
                curY += lineSpacing;
                currentLine = currentWord;
            }
            else
            {
                if (!currentLine.empty()) currentLine += " ";
                currentLine += currentWord;
            }
            currentWord = "";

            if (isNewline)
            {
                if (!currentLine.empty())
                {
                    drawText(renderer, currentLine, x, curY, scale, color);
                    curY += lineSpacing;
                    currentLine = "";
                }
            }
        };

        for (size_t i = 0; i < text.length(); ++i)
        {
            char c = text[i];
            if (c == ' ')
            {
                flushWord(false);
            }
            else if (c == '\n')
            {
                flushWord(true);
            }
            else
            {
                currentWord += c;
            }
        }

        if (!currentWord.empty())
        {
            flushWord(false);
        }

        if (!currentLine.empty())
        {
            drawText(renderer, currentLine, x, curY, scale, color);
            curY += lineSpacing;
        }

        return curY;
    }

    float getTextHeightWrapped(const std::string& text, float maxWidth, float scale, float lineSpacing)
    {
        float totalHeight = 0.0f;
        float charW = 9.0f * scale;
        
        std::string currentLine = "";
        std::string currentWord = "";

        auto flushWord = [&](bool isNewline) {
            float wordWidth = currentWord.length() * charW;
            float lineWithWordWidth = (currentLine.empty() ? 0.0f : (currentLine.length() + 1) * charW) + wordWidth;

            if (!currentLine.empty() && lineWithWordWidth > maxWidth)
            {
                totalHeight += lineSpacing;
                currentLine = currentWord;
            }
            else
            {
                if (!currentLine.empty()) currentLine += " ";
                currentLine += currentWord;
            }
            currentWord = "";

            if (isNewline)
            {
                if (!currentLine.empty())
                {
                    totalHeight += lineSpacing;
                    currentLine = "";
                }
            }
        };

        for (size_t i = 0; i < text.length(); ++i)
        {
            char c = text[i];
            if (c == ' ')
            {
                flushWord(false);
            }
            else if (c == '\n')
            {
                flushWord(true);
            }
            else
            {
                currentWord += c;
            }
        }

        if (!currentWord.empty())
        {
            flushWord(false);
        }

        if (!currentLine.empty())
        {
            totalHeight += lineSpacing;
        }

        return totalHeight;
    }
